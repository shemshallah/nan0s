#!/usr/bin/env python3
"""nan16_embed_tree.py OUT.h [--file NAME=PATH ...] [--tree DIR=PREFIX ...]

Emit a C table of embedded read-only files for the guest VFS.  Used by the
tcc1 raw-source gate: the compiler reads /usr/include/... and /work/... from
the same flat VFS the product uses.  Build input only.
"""
import argparse
import json
import os
import sys


def emit_data(out, ident, data):
    out.write("static const unsigned char %s[] = {\n" % ident)
    if not data:
        out.write("0,\n")
    for i in range(0, len(data), 24):
        out.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--file", action="append", default=[],
                    help="NAME=PATH")
    ap.add_argument("--tree", action="append", default=[],
                    help="DIR=PREFIX")
    args = ap.parse_args()

    files = []
    for spec in args.file:
        name, path = spec.split("=", 1)
        files.append((name, path))
    for spec in args.tree:
        root, prefix = spec.split("=", 1)
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames.sort()
            for fn in sorted(filenames):
                path = os.path.join(dirpath, fn)
                rel = os.path.relpath(path, root).replace(os.sep, "/")
                name = prefix.rstrip("/") + "/" + rel
                files.append((name, path))

    files.sort()
    with open(args.out, "w") as out:
        out.write("/* generated by tools/nan16_embed_tree.py; build input only */\n")
        out.write("#ifndef NAN16_EMBED_TREE_H\n#define NAN16_EMBED_TREE_H\n")
        out.write("struct nan16_embed_file { const char *name;"
                  " const unsigned char *data; unsigned len; };\n")
        entries = []
        for i, (name, path) in enumerate(files):
            data = open(path, "rb").read()
            ident = "nf%d" % i
            emit_data(out, ident, data)
            entries.append((name, ident, len(data)))
        out.write("static const struct nan16_embed_file nan16_embed_files[] = {\n")
        for name, ident, n in entries:
            out.write("  { %s, %s, %uu },\n" % (json.dumps(name), ident, n))
        out.write("};\n")
        out.write("#define NAN16_EMBED_COUNT %du\n" % len(entries))
        out.write("#endif\n")


if __name__ == "__main__":
    main()
