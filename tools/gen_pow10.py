#!/usr/bin/env python3
"""Generate nan16_pow10.h: correctly rounded binary64 values of 10^k.

Python's decimal-to-float conversion is correctly rounded, so each entry is
the nearest IEEE-754 binary64 value to 10^k.  The table is stored as raw bit
patterns so the guest compiler never has to parse a decimal float constant
with the very routine that is being bootstrapped.
"""
import struct
import sys

COUNT = 309
DEFAULT = "third_party/nan16-libc/src/nan16_pow10.h"


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    lines = [
        "/* Generated by tools/gen_pow10.py; do not edit.",
        "   Correctly rounded IEEE-754 binary64 bit patterns for 10^k,",
        "   k = 0..308.  Index with the decimal exponent in strtod. */",
        "static const unsigned long long nan16_pow10_bits[%d] = {" % COUNT,
    ]
    row = []
    for k in range(COUNT):
        row.append("0x%016XULL," % bits(float("1e%d" % k)))
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
