#!/usr/bin/env python3
"""nan16_build_job.py - generate the guest compiler's build-job table.

The generic guest build driver (third_party/nan16-libc/src/guest_build_driver.c)
compiles one or more jobs from the guest VFS.  A job lists include paths,
preprocessor defines, source files, output name and the fixed guest addresses
where the flat cartridge is copied.  This tool turns a small text spec into a C
header; it emits only strings and integers, never source bytes.

Spec syntax (one directive per line, '#' comments):
  job NAME OUTPUT SIZE_ADDR COPY_ADDR
    include /work/libc
    define  GUEST=1
    runtime 1
    source  /work/libc/libc.c

COPY_ADDR receives the cartridge bytes; SIZE_ADDR receives a 32-bit length.
"""
import argparse
import json
import shlex
import sys


class Job:
    def __init__(self, name, output, size_addr, copy_addr):
        self.name = name
        self.output = output
        self.size_addr = size_addr
        self.copy_addr = copy_addr
        self.includes = []
        self.defines = []
        self.sources = []
        self.runtime = 1


def parse(path):
    jobs = []
    cur = None
    with open(path) as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = shlex.split(line)
            if parts[0] == "job":
                if len(parts) != 5:
                    sys.exit("%s:%d: want 'job NAME OUTPUT SIZE_ADDR COPY_ADDR'"
                             % (path, lineno))
                cur = Job(*parts[1:])
                jobs.append(cur)
            elif parts[0] in ("include", "define", "source", "runtime"):
                if cur is None:
                    sys.exit("%s:%d: directive before job" % (path, lineno))
                if parts[0] == "runtime":
                    cur.runtime = int(parts[1], 0)
                elif len(parts) != 2:
                    sys.exit("%s:%d: want '%s VALUE'" % (path, lineno, parts[0]))
                else:
                    getattr(cur, parts[0] + "s").append(parts[1])
            else:
                sys.exit("%s:%d: unknown directive %s" % (path, lineno, parts[0]))
    if not jobs:
        sys.exit("%s: no jobs" % path)
    return jobs


def emit_array(out, ident, values):
    if not values:
        out.write("static const char *const %s[] = { 0 };\n" % ident)
        return
    out.write("static const char *const %s[] = {\n" % ident)
    for v in values:
        out.write("  %s,\n" % json.dumps(v))
    out.write("};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("out")
    args = ap.parse_args()
    jobs = parse(args.spec)

    with open(args.out, "w") as out:
        out.write("/* generated by tools/nan16_build_job.py; build input only */\n")
        out.write("#ifndef NAN16_BUILD_JOB_H\n#define NAN16_BUILD_JOB_H\n")
        out.write("struct guest_build_job {\n"
                  "  const char *name;\n"
                  "  const char *output;\n"
                  "  unsigned size_addr;\n"
                  "  unsigned copy_addr;\n"
                  "  const char *const *includes;\n"
                  "  unsigned ninclude;\n"
                  "  const char *const *defines;\n"
                  "  unsigned ndefine;\n"
                  "  const char *const *sources;\n"
                  "  unsigned nsource;\n"
                  "  int runtime;\n"
                  "};\n")
        for i, j in enumerate(jobs):
            emit_array(out, "guest_job%d_includes" % i, j.includes)
            emit_array(out, "guest_job%d_defines" % i, j.defines)
            emit_array(out, "guest_job%d_sources" % i, j.sources)
        out.write("static const struct guest_build_job guest_build_jobs[] = {\n")
        for i, j in enumerate(jobs):
            out.write("  { %s, %s, %su, %su, guest_job%d_includes, %du,"
                      " guest_job%d_defines, %du, guest_job%d_sources, %du, %d },\n"
                      % (json.dumps(j.name), json.dumps(j.output),
                         j.size_addr, j.copy_addr, i, len(j.includes), i,
                         len(j.defines), i, len(j.sources), j.runtime))
        out.write("};\n")
        out.write("#define GUEST_BUILD_JOB_COUNT %du\n" % len(jobs))
        out.write("#endif\n")


if __name__ == "__main__":
    main()
