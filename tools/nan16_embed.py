#!/usr/bin/env python3
"""nan16_embed.py OUT.h NAME=FILE [NAME=FILE ...]

Embed source bytes as C arrays for the tcc2 compile driver.  The generated
header is build input only; it is written into the temporary gate directory.
"""
import sys

if len(sys.argv) < 2:
    print(__doc__.strip(), file=sys.stderr)
    sys.exit(2)
out = sys.argv[1]
with open(out, "w") as o:
    o.write("/* generated by tools/nan16_embed.py; build input only */\n")
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = open(path, "rb").read()
        o.write("static const unsigned char %s[] = {\n" % name)
        for i in range(0, len(data), 16):
            o.write(",".join(str(b) for b in data[i:i + 16]) + ",\n")
        o.write("};\n")
        o.write("static const unsigned int %s_len = %u;\n" % (name, len(data)))
