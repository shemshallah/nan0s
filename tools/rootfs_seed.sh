#!/bin/sh
# tools/rootfs_seed.sh - generate the NANIX / seed table from nanfs/.
#
# The committed nanfs/ directory is the source of truth for the files NANIX
# seeds into its RAM filesystem at boot.  This emits raw NaN16:
#   rootfs_seed_all: LA r1,@path ; SHL r1,r1,2 ; LA r2,@data ; CALL @fs_seed
# The paths are the directory entries; contents are .str data (text files).
set -eu
cd "$(dirname "$0")/.."
export LC_ALL=C
OUT=src/nan/rootfs_seed.nas
TMP="$OUT.tmp"
: > "$TMP"

echo "; generated by tools/rootfs_seed.sh from nanfs/ - do not edit" >> "$TMP"
echo "rootfs_seed_all:" >> "$TMP"
echo "  ST r15,r14,0" >> "$TMP"
echo "  ADDI r14,r14,9" >> "$TMP"

i=0
for f in nanfs/*; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  printf '  LA r1,@rootfs_p%d\n  SHL r1,r1,2\n  LA r2,@rootfs_d%d\n  CALL @fs_seed\n' "$i" "$i" >> "$TMP"
  i=$((i + 1))
done
echo "  ADDI r14,r14,-9" >> "$TMP"
echo "  LD r15,r14,0" >> "$TMP"
echo "  RET" >> "$TMP"

i=0
for f in nanfs/*; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  printf 'rootfs_p%d:\n.str "/%s"\n' "$i" "$name" >> "$TMP"
  printf 'rootfs_d%d:\n.str "' "$i" >> "$TMP"
  if [ -s "$f" ]; then
    awk '{ gsub(/\\/, "\\\\"); gsub(/"/, "\\\""); printf "%s\\n", $0 }' "$f" >> "$TMP"
  fi
  printf '"\n' >> "$TMP"
  i=$((i + 1))
done

mv "$TMP" "$OUT"
echo "rootfs_seed: $(find nanfs -maxdepth 1 -type f | wc -l) files -> $OUT"
